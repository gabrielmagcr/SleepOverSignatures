function groupedFlags() {
  if (!flags.length) return "";

  const kinds = [];
  flags.forEach((f) => {
    let g = kinds.find((k) => k.kind === f.kind);
    if (!g) { g = { kind: f.kind, items: [] }; kinds.push(g); }
    g.items.push(f);
  });

  const rows = kinds.map((g) => {
    const copy = FLAG_COPY[g.kind] || { title: g.kind, body: "" };

    // Regions, with a count, when the note covers several people; plain names
    // when it is only one or two.
    let who;
    if (g.items.length > 2) {
      const byRegion = [];
      g.items.forEach((it) => {
        let r = byRegion.find((x) => x.region === it.region);
        if (!r) { r = { region: it.region, n: 0 }; byRegion.push(r); }
        r.n++;
      });
      who = byRegion.map((r) => `${esc(r.region)} (${r.n})`).join(", ");
    } else {
      who = g.items.map((it) => `${esc(it.name)} &mdash; ${esc(it.region)}`).join("; ");
    }

    const detail = g.items.find((it) => it.detail)?.detail;

    return `<li>
        <b>${esc(copy.title)}</b> &mdash; ${g.items.length} ${g.items.length === 1 ? "person" : "people"}: ${who}.
        <span class="why">${copy.body}${detail ? " " + esc(detail) + "." : ""}</span>
      </li>`;
  });

  return `<details class="flags" open>
    <summary>${ICON.alert}<span>${kinds.length} thing${kinds.length === 1 ? "" : "s"} to look at before sign-off</span></summary>
    <ul>
      ${rows.join("\n      ")}
    </ul>
  </details>`;
}

